BEGIN;

CREATE SCHEMA lich_ksktd;
SET search_path TO lich_ksktd, public;

-- Khoa phòng tham gia khám sức khỏe toàn dân. Đây là đơn vị được phân công
-- theo tua, mỗi khoa phòng là một hàng trong bảng lịch.
CREATE TABLE departments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE system_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_salt TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin', 'dieu_phoi', 'khoa_phong')),
  department_id BIGINT REFERENCES departments(id) ON DELETE SET NULL,
  full_name TEXT NOT NULL DEFAULT '',
  signature TEXT,
  disabled SMALLINT NOT NULL DEFAULT 0 CHECK (disabled IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_sessions (
  id TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Ngày làm việc do quản lý mở. Lịch không còn chạy liên tục T2-CN, chỉ những
-- ngày có ở đây mới xuất hiện thành cột trong bảng lịch.
CREATE TABLE work_days (
  date DATE PRIMARY KEY,
  session TEXT NOT NULL CHECK (session IN ('morning', 'afternoon', 'full')),
  note TEXT,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Một ô trong bảng lịch: khoa phòng nào làm ngày nào, kèm người trực tiếp đi
-- làm hôm đó do chính khoa phòng điền.
CREATE TABLE assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date DATE NOT NULL REFERENCES work_days(date) ON DELETE CASCADE ON UPDATE CASCADE,
  department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
  person_name TEXT NOT NULL DEFAULT '',
  person_phone TEXT NOT NULL DEFAULT '',
  member_order INTEGER NOT NULL DEFAULT 0,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (date, department_id)
);

-- Hàng đầu của bảng lịch: điều phối nào phụ trách ngày làm nào. Điều phối
-- được xếp thủ công, không chạy theo tua như khoa phòng.
CREATE TABLE coordinator_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date DATE NOT NULL REFERENCES work_days(date) ON DELETE CASCADE ON UPDATE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  member_order INTEGER NOT NULL DEFAULT 0,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (date, user_id)
);

-- Yêu cầu đổi ngày làm giữa hai điều phối. Chỉ đổi khi người nhận đồng ý.
CREATE TABLE swap_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
  assignment_id_1 BIGINT NOT NULL REFERENCES coordinator_assignments(id) ON DELETE CASCADE,
  user_id_1 BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  date_1 DATE NOT NULL,
  assignment_id_2 BIGINT NOT NULL REFERENCES coordinator_assignments(id) ON DELETE CASCADE,
  user_id_2 BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  date_2 DATE NOT NULL,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  expires_at TIMESTAMPTZ,
  decided_at TIMESTAMPTZ,
  decided_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Cấu hình tua dùng chung cho toàn bộ lịch, chỉ có một dòng.
CREATE TABLE rotation_config (
  id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  start_date DATE NOT NULL,
  enabled SMALLINT NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
  updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE rotation_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turn_index INTEGER NOT NULL,
  department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
  member_order INTEGER NOT NULL DEFAULT 0,
  UNIQUE (turn_index, department_id)
);

CREATE TABLE audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  entity_type TEXT NOT NULL,
  entity_id BIGINT,
  summary TEXT NOT NULL,
  payload TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Báo cáo làm việc của một ngày làm: số liệu buổi khám và chữ ký chốt của
-- điều phối.
CREATE TABLE work_reports (
  date DATE PRIMARY KEY REFERENCES work_days(date) ON DELETE CASCADE ON UPDATE CASCADE,
  report_date DATE NOT NULL,
  report_time TEXT NOT NULL,
  so_luot_kham INTEGER NOT NULL DEFAULT 0,
  so_ho_so INTEGER NOT NULL DEFAULT 0,
  vat_tu TEXT NOT NULL DEFAULT '',
  su_co TEXT NOT NULL DEFAULT '',
  de_xuat TEXT NOT NULL DEFAULT '',
  signature_dieu_phoi TEXT,
  signature_dieu_phoi_name TEXT,
  signature_dieu_phoi_at TIMESTAMPTZ,
  signature_dieu_phoi_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Điểm danh và ký tên của từng khoa phòng trong ngày làm.
CREATE TABLE work_report_attendance (
  date DATE NOT NULL REFERENCES work_days(date) ON DELETE CASCADE ON UPDATE CASCADE,
  department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
  present SMALLINT NOT NULL DEFAULT 0 CHECK (present IN (0, 1)),
  note TEXT,
  signature TEXT,
  signature_name TEXT,
  signature_at TIMESTAMPTZ,
  signature_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (date, department_id)
);

CREATE TABLE notification_reads (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  notification_id TEXT NOT NULL,
  read_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, notification_id)
);

CREATE INDEX idx_sessions_user ON user_sessions(user_id);
CREATE INDEX idx_sessions_expires ON user_sessions(expires_at);
CREATE INDEX idx_assignments_date ON assignments(date);
CREATE INDEX idx_assignments_department ON assignments(department_id);
CREATE INDEX idx_assignments_created_by ON assignments(created_by);
CREATE INDEX idx_assignments_updated_by ON assignments(updated_by);
CREATE INDEX idx_work_days_created_by ON work_days(created_by);
CREATE INDEX idx_coordinator_assignments_date ON coordinator_assignments(date);
CREATE INDEX idx_coordinator_assignments_user ON coordinator_assignments(user_id);
CREATE INDEX idx_coordinator_assignments_created_by ON coordinator_assignments(created_by);
CREATE INDEX idx_coordinator_assignments_updated_by ON coordinator_assignments(updated_by);
CREATE INDEX idx_swap_requests_token_status ON swap_requests(token, status, expires_at);
CREATE INDEX idx_swap_requests_recipient ON swap_requests(user_id_2, status);
CREATE INDEX idx_swap_requests_assignment_1 ON swap_requests(assignment_id_1);
CREATE INDEX idx_swap_requests_assignment_2 ON swap_requests(assignment_id_2);
CREATE INDEX idx_swap_requests_users ON swap_requests(user_id_1);
CREATE INDEX idx_swap_requests_created_by ON swap_requests(created_by);
CREATE INDEX idx_swap_requests_decided_by ON swap_requests(decided_by);
CREATE INDEX idx_rotation_members_department ON rotation_members(department_id);
CREATE INDEX idx_rotation_config_updated_by ON rotation_config(updated_by);
CREATE INDEX idx_audit_created ON audit_logs(created_at);
CREATE INDEX idx_audit_actor ON audit_logs(actor_user_id);
CREATE INDEX idx_users_department ON users(department_id);
CREATE INDEX idx_reports_signature_user ON work_reports(signature_dieu_phoi_user_id);
CREATE INDEX idx_attendance_department ON work_report_attendance(department_id);
CREATE INDEX idx_attendance_signature_user ON work_report_attendance(signature_user_id);

INSERT INTO system_settings (key, value) VALUES
  ('lock_person_on_workday', '0');

REVOKE ALL ON SCHEMA lich_ksktd FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA lich_ksktd FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA lich_ksktd TO lich_ksktd_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA lich_ksktd TO lich_ksktd_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA lich_ksktd TO lich_ksktd_app;

DO $security$
DECLARE
  table_name TEXT;
BEGIN
  FOR table_name IN
    SELECT tablename FROM pg_tables WHERE schemaname = 'lich_ksktd'
  LOOP
    EXECUTE format('ALTER TABLE lich_ksktd.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('ALTER TABLE lich_ksktd.%I FORCE ROW LEVEL SECURITY', table_name);
    EXECUTE format(
      'CREATE POLICY %I ON lich_ksktd.%I FOR ALL TO lich_ksktd_app USING (true) WITH CHECK (true)',
      table_name || '_app_access',
      table_name
    );
  END LOOP;
END
$security$;

ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA lich_ksktd
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO lich_ksktd_app;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA lich_ksktd
  GRANT USAGE, SELECT ON SEQUENCES TO lich_ksktd_app;

COMMIT;
