BEGIN;

CREATE SCHEMA lich_truc;
SET search_path TO lich_truc, public;

CREATE TABLE schedule_units (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  section TEXT NOT NULL CHECK (section IN ('I', 'II', 'III')),
  label TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('duty_common', 'duty_bs', 'duty_ktv', 'leave', 'work_bs', 'work_ktv')),
  max_per_day INTEGER,
  sort_order INTEGER NOT NULL,
  computed SMALLINT NOT NULL DEFAULT 0 CHECK (computed IN (0, 1))
);

CREATE TABLE system_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE blocked_leave_days (
  date DATE PRIMARY KEY
);

CREATE TABLE staff (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family_middle_name TEXT NOT NULL DEFAULT '',
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('BS', 'KTV', 'TKYK')),
  active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  leave_balance INTEGER CHECK (leave_balance >= 0),
  leave_balance_from DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (name, type)
);

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_salt TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin', 'bs', 'ktv', 'tkyk')),
  staff_id BIGINT REFERENCES staff(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  signature TEXT,
  disabled SMALLINT NOT NULL DEFAULT 0 CHECK (disabled IN (0, 1))
);

CREATE TABLE user_sessions (
  id TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE unit_rotation_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unit_id BIGINT NOT NULL REFERENCES schedule_units(id) ON DELETE CASCADE,
  turn_index INTEGER NOT NULL,
  staff_id BIGINT NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
  member_order INTEGER NOT NULL DEFAULT 0,
  UNIQUE (unit_id, turn_index, staff_id)
);

CREATE TABLE schedule_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unit_id BIGINT NOT NULL REFERENCES schedule_units(id) ON DELETE CASCADE,
  date DATE NOT NULL,
  staff_id BIGINT NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
  slot INTEGER NOT NULL DEFAULT 0,
  confirmed SMALLINT NOT NULL DEFAULT 0 CHECK (confirmed IN (0, 1)),
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (unit_id, date, slot),
  UNIQUE (unit_id, date, staff_id)
);

CREATE TABLE leave_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id BIGINT NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
  reason TEXT,
  status TEXT NOT NULL DEFAULT 'approved' CHECK (status IN ('approved', 'cancelled', 'pending')),
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  requested_dates TEXT,
  decision TEXT CHECK (decision IN ('approved', 'rejected', 'cancelled')),
  decided_at TIMESTAMPTZ,
  decided_by BIGINT REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE leave_days (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES leave_requests(id) ON DELETE CASCADE,
  staff_id BIGINT NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
  date DATE NOT NULL,
  staff_type TEXT NOT NULL CHECK (staff_type IN ('BS', 'KTV', 'TKYK')),
  UNIQUE (staff_id, date)
);

CREATE TABLE audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  entity_type TEXT NOT NULL,
  entity_id BIGINT,
  summary TEXT NOT NULL,
  payload TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE unit_rotations (
  unit_id BIGINT PRIMARY KEY REFERENCES schedule_units(id) ON DELETE CASCADE,
  start_date DATE NOT NULL,
  enabled SMALLINT NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
  updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  mode TEXT NOT NULL DEFAULT 'daily' CHECK (mode IN ('daily', 'weekly'))
);

CREATE TABLE swap_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token TEXT NOT NULL UNIQUE,
  assignment_id_1 BIGINT NOT NULL,
  staff_id_1 BIGINT NOT NULL,
  unit_id_1 BIGINT NOT NULL,
  date_1 DATE NOT NULL,
  slot_1 INTEGER NOT NULL,
  assignment_id_2 BIGINT NOT NULL,
  staff_id_2 BIGINT NOT NULL,
  unit_id_2 BIGINT NOT NULL,
  date_2 DATE NOT NULL,
  slot_2 INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ
);

CREATE TABLE duty_reports (
  date DATE PRIMARY KEY,
  report_date DATE NOT NULL,
  report_time TEXT NOT NULL,
  bs_truc TEXT,
  ktv_truc TEXT,
  xq_khoa INTEGER NOT NULL DEFAULT 0,
  xq_giuong INTEGER NOT NULL DEFAULT 0,
  mri INTEGER NOT NULL DEFAULT 0,
  ct_scan INTEGER NOT NULL DEFAULT 0,
  thuoc_su_dung TEXT,
  ca_kho TEXT,
  thiet_bi TEXT,
  an_ninh TEXT,
  signature_bs TEXT,
  signature_bs_name TEXT,
  signature_bs_at TIMESTAMPTZ,
  signature_ktv TEXT,
  signature_ktv_name TEXT,
  signature_ktv_at TIMESTAMPTZ,
  signature_lanhdao TEXT,
  signature_lanhdao_name TEXT,
  signature_lanhdao_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  signature_bs_user_id BIGINT REFERENCES users(id),
  signature_ktv_user_id BIGINT REFERENCES users(id),
  signature_lanhdao_user_id BIGINT REFERENCES users(id)
);

CREATE TABLE notification_reads (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  notification_id TEXT NOT NULL,
  read_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, notification_id)
);

CREATE INDEX idx_sessions_user ON user_sessions(user_id);
CREATE INDEX idx_sessions_expires ON user_sessions(expires_at);
CREATE INDEX idx_assignments_date ON schedule_assignments(date);
CREATE INDEX idx_assignments_unit_date ON schedule_assignments(unit_id, date);
CREATE INDEX idx_assignments_staff ON schedule_assignments(staff_id);
CREATE INDEX idx_assignments_created_by ON schedule_assignments(created_by);
CREATE INDEX idx_assignments_updated_by ON schedule_assignments(updated_by);
CREATE INDEX idx_leave_requests_staff ON leave_requests(staff_id);
CREATE INDEX idx_leave_requests_created_by ON leave_requests(created_by);
CREATE INDEX idx_leave_requests_decided_by ON leave_requests(decided_by);
CREATE INDEX idx_leave_days_request ON leave_days(request_id);
CREATE INDEX idx_leave_days_date_type ON leave_days(date, staff_type);
CREATE INDEX idx_audit_created ON audit_logs(created_at);
CREATE INDEX idx_audit_actor ON audit_logs(actor_user_id);
CREATE INDEX idx_rotation_members_staff ON unit_rotation_members(staff_id);
CREATE INDEX idx_rotations_updated_by ON unit_rotations(updated_by);
CREATE INDEX idx_swap_requests_token_status ON swap_requests(token, status, expires_at);
CREATE INDEX idx_swap_requests_created_by ON swap_requests(created_by);
CREATE INDEX idx_notification_reads_user ON notification_reads(user_id, read_at);
CREATE INDEX idx_users_staff ON users(staff_id);
CREATE INDEX idx_reports_signature_bs_user ON duty_reports(signature_bs_user_id);
CREATE INDEX idx_reports_signature_ktv_user ON duty_reports(signature_ktv_user_id);
CREATE INDEX idx_reports_signature_lanhdao_user ON duty_reports(signature_lanhdao_user_id);

REVOKE ALL ON SCHEMA lich_truc FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA lich_truc FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA lich_truc TO lich_truc_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA lich_truc TO lich_truc_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA lich_truc TO lich_truc_app;

DO $security$
DECLARE
  table_name TEXT;
BEGIN
  FOR table_name IN
    SELECT tablename FROM pg_tables WHERE schemaname = 'lich_truc'
  LOOP
    EXECUTE format('ALTER TABLE lich_truc.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('ALTER TABLE lich_truc.%I FORCE ROW LEVEL SECURITY', table_name);
    EXECUTE format(
      'CREATE POLICY %I ON lich_truc.%I FOR ALL TO lich_truc_app USING (true) WITH CHECK (true)',
      table_name || '_app_access',
      table_name
    );
  END LOOP;
END
$security$;

ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA lich_truc
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO lich_truc_app;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA lich_truc
  GRANT USAGE, SELECT ON SEQUENCES TO lich_truc_app;

COMMIT;
